// Rebuild only when source animation sheets change. Runtime uses these compact
// alpha-clear spans instead of scanning millions of pixels on each device.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/systems/EnemyRunTexture.ts'), 'utf8');
const compiled = ts.transpileModule(source.replace(/^import .*SpriteFragmentRuns.*;\r?\n/m, ''), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText;
const exportsObject = {};
new Function('exports', compiled)(exportsObject);
const names = ['goon-red-run-sheet', 'goon-hoodie-run-sheet', 'goon-club-run-sheet',
  'goon-red-attack-sheet', 'goon-hoodie-attack-sheet', 'goon-club-attack-sheet',
  'kibera-stone-goon-sprint-sheet', 'kibera-shield-goon-sprint-sheet',
  'mbavu-defeat-fall-fullboots-sheet', 'chapati-health-pickup-sheet'];
const result = {};
for (const name of names) {
  const filename = path.join(root, 'src/assets/optimized/gameplay/generated', name + '.webp');
  const raw = execFileSync('python', ['-c', 'from PIL import Image;import sys;sys.stdout.buffer.write(Image.open(sys.argv[1]).convert("RGBA").tobytes())', filename], { maxBuffer: 20_000_000 });
  const width = name.startsWith('mbavu') ? 512 : 384;
  const fullWidth = width * 8, height = 384, spans = [];
  for (let frame = 0; frame < 8; frame++) {
    const pixels = new Uint8ClampedArray(width * height * 4);
    for (let y = 0; y < height; y++) pixels.set(raw.subarray((y * fullWidth + frame * width) * 4, (y * fullWidth + (frame + 1) * width) * 4), y * width * 4);
    exportsObject.removeDetachedPixels(pixels, width, height);
    for (let y = 0; y < height; y++) {
      let start = -1;
      for (let x = 0; x <= width; x++) {
        const index = y * fullWidth + frame * width + x;
        const removed = x < width && raw[index * 4 + 3] > 0 && pixels[(y * width + x) * 4 + 3] === 0;
        if (removed && start < 0) start = index;
        if (!removed && start >= 0) { spans.push(start, index - start); start = -1; }
      }
    }
  }
  const key = name.startsWith('mbavu') ? 'gameplay-mbavu-defeat-fall-sheet' : 'gameplay-' + name;
  result[key] = spans;
  console.log(`${key}: ${spans.length / 2} removal spans`);
}
const output = '// Generated by scripts/prepare-sprite-cleanup.cjs. Source frame positions are unchanged.\nexport const SPRITE_FRAGMENT_RUNS: Record<string, readonly number[]> = ' + JSON.stringify(result) + ';\n';
const target = path.join(root, 'src/systems/SpriteFragmentRuns.ts');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Sprite cleanup data is stale. Run node scripts/prepare-sprite-cleanup.cjs');
  console.log('All sprite masks match the original pixel-cleanup algorithm.');
} else fs.writeFileSync(target, output);
